"""Premier League performance dashboard.

Run locally: python app.py
Vercel WSGI entry point: app:app
Data: data/premier_league_teams.csv (generated by prepare_data.py)
"""
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
from dash import Dash, Input, Output, State, ctx, dcc, html

DATA_PATH = Path(__file__).resolve().parent / "data" / "premier_league_teams.csv"
if not DATA_PATH.is_file():
    raise FileNotFoundError(
        f"Missing dataset: {DATA_PATH}. Run prepare_data.py and commit the data folder."
    )

matches = pd.read_csv(DATA_PATH)
REQUIRED = {"Season", "Team", "Outcome", "GoalsFor", "GoalsAgainst", "Points"}
missing = REQUIRED - set(matches.columns)
if missing:
    raise ValueError(f"Dataset missing columns: {sorted(missing)}")

matches = matches.dropna(subset=["Season", "Team", "Outcome"]).copy()
for column in ("GoalsFor", "GoalsAgainst", "Points"):
    matches[column] = pd.to_numeric(matches[column], errors="coerce")
matches = matches.dropna(subset=["GoalsFor", "GoalsAgainst", "Points"])
matches = matches[matches["Outcome"].isin(["Win", "Draw", "Loss"])].copy()
if matches.empty:
    raise ValueError("No valid Premier League team-match records found.")
matches["Season"] = matches["Season"].astype(str)

for outcome in ("Win", "Draw", "Loss"):
    matches[f"{outcome}Count"] = (matches["Outcome"] == outcome).astype(int)

stats = (
    matches.groupby(["Season", "Team"], as_index=False)
    .agg(
        Played=("Outcome", "size"),
        Wins=("WinCount", "sum"),
        Draws=("DrawCount", "sum"),
        Losses=("LossCount", "sum"),
        GoalsFor=("GoalsFor", "sum"),
        GoalsAgainst=("GoalsAgainst", "sum"),
        Points=("Points", "sum"),
    )
)
stats["GoalDifference"] = stats["GoalsFor"] - stats["GoalsAgainst"]
seasons = sorted(stats["Season"].unique(), reverse=True)

# Vermillion is exclusively a focus highlight, never an outcome category.
SELECTION = "#D55E00"
NEUTRAL = "#8293A6"
DARK = "#213246"
OUTCOME_COLORS = {"Win": "#0072B2", "Draw": "#E69F00", "Loss": "#CC79A7"}
OUTCOME_FIELDS = [("Win", "Wins"), ("Draw", "Draws"), ("Loss", "Losses")]

# Scroll-wheel zoom and accidental chart zoom remain disabled.
GRAPH_CONFIG = {
    "responsive": True,
    "scrollZoom": False,
    "displaylogo": False,
    "doubleClick": False,
    "modeBarButtonsToRemove": ["toImage", "lasso2d", "select2d", "zoom2d", "pan2d", "autoScale2d", "resetScale2d"],
}


def season_table(season):
    """Points ranking with standard goal-difference/goals-scored tiebreaks."""
    return (
        stats.loc[stats["Season"] == season]
        .sort_values(
            ["Points", "GoalDifference", "GoalsFor", "Team"],
            ascending=[False, False, False, True],
        )
        .reset_index(drop=True)
    )


def metric_card(label, value):
    return html.Div(
        className="kpi-card",
        children=[
            html.Span(label, className="kpi-label"),
            html.Strong(f"{value:,}", className="kpi-value"),
        ],
    )


def common_layout(fig):
    fig.update_layout(
        autosize=True,
        margin=dict(l=12, r=12, t=12, b=12),
        paper_bgcolor="#FFFFFF",
        plot_bgcolor="#FFFFFF",
        font=dict(family="Arial, Helvetica, sans-serif", size=12, color=DARK),
        hoverlabel=dict(bgcolor="white", font_size=12, font_color=DARK),
        transition=dict(duration=0),
        uirevision="layout-fixed",
    )
    return fig


def goals_bubble_figure(table, chosen, season):
    """2D bubble chart: goals scored vs conceded, bubble area = wins."""
    fig = go.Figure()
    labels = {
        table.loc[table["GoalsFor"].idxmax(), "Team"],
        table.loc[table["GoalsAgainst"].idxmin(), "Team"],
        table.loc[table["Points"].idxmax(), "Team"],
    }
    if chosen:
        labels.add(chosen)

    # Same wins-to-marker-area mapping for selected and other teams.
    largest = max(1, int(table["Wins"].max()))
    size_ref = 2 * largest / (38 ** 2)

    def add_group(frame, name, selected=False):
        if frame.empty:
            return
        custom = frame[["Team", "Wins", "Points", "Played", "GoalDifference"]].to_numpy()
        fig.add_trace(go.Scatter(
            x=frame["GoalsFor"],
            y=frame["GoalsAgainst"],
            mode="markers+text",
            name=name,
            text=[team if team in labels else "" for team in frame["Team"]],
            textposition="top center",
            textfont=dict(size=11, color=DARK),
            customdata=custom,
            marker=dict(
                size=frame["Wins"].clip(lower=1).tolist(),
                sizemode="area", sizeref=size_ref, sizemin=7,
                color=SELECTION if selected else NEUTRAL,
                symbol="diamond" if selected else "circle",
                opacity=0.96 if selected else 0.72,
                line=dict(color=DARK, width=2 if selected else 0.7),
            ),
            hovertemplate=(
                "<b>%{customdata[0]}</b>"
                "<br>Goals scored: %{x}"
                "<br>Goals conceded: %{y}"
                "<br>Wins: %{customdata[1]}"
                "<br>Points: %{customdata[2]}"
                "<br>Matches: %{customdata[3]}"
                "<br>Goal difference: %{customdata[4]}<extra></extra>"
            ),
        ))

    others = table if chosen is None else table.loc[table["Team"] != chosen]
    add_group(others, "All teams" if chosen is None else "Other teams")
    if chosen:
        add_group(table.loc[table["Team"] == chosen], "Selected club", True)
    common_layout(fig)
    fig.update_layout(
        margin=dict(l=64, r=30, t=32, b=54),
        showlegend=bool(chosen),
        legend=dict(orientation="h", x=0.02, y=1.12),
        dragmode=False,
        uirevision=f"goals-{season}",
    )
    fig.update_xaxes(title="Goals scored", fixedrange=True, gridcolor="#E9EEF4", zeroline=False)
    fig.update_yaxes(title="Goals conceded", fixedrange=True, gridcolor="#E9EEF4", zeroline=False)
    return fig


def points_figure(table, chosen):
    """Fixed league order in a horizontally scrollable view."""
    order = table["Team"].tolist()
    custom = table[["Team", "Played", "Wins", "Draws", "Losses", "GoalDifference"]].to_numpy()
    fig = go.Figure(
        go.Bar(
            orientation="h", y=order, x=table["Points"], customdata=custom,
            marker=dict(
                color=[SELECTION if t == chosen else NEUTRAL for t in order],
                line=dict(color=DARK, width=[2 if t == chosen else 0 for t in order]),
            ),
            text=table["Points"].astype(int), textposition="outside", cliponaxis=False,
            hovertemplate=(
                "<b>%{customdata[0]}</b><br>Points: %{x}"
                "<br>Played: %{customdata[1]} | Wins: %{customdata[2]}"
                "<br>Draws: %{customdata[3]} | Losses: %{customdata[4]}"
                "<br>Goal difference: %{customdata[5]}<extra></extra>"
            ),
        )
    )
    common_layout(fig)
    fig.update_layout(
        height=610,
        margin=dict(l=125, r=45, t=10, b=45),
        showlegend=False, bargap=0.23,
        dragmode=False,
    )
    fig.update_yaxes(categoryorder="array", categoryarray=order, autorange="reversed", fixedrange=True)
    fig.update_xaxes(title="Points", range=[0, max(5, float(table["Points"].max()) * 1.13)], fixedrange=True,
                     showgrid=True, gridcolor="#E9EEF4", zeroline=False)
    return fig


def outcomes_figure(table, chosen):
    """100% stacked per-team match outcomes; no symmetric overall donut."""
    order = table["Team"].tolist()
    fig = go.Figure()
    for outcome, field in OUTCOME_FIELDS:
        percentages = 100 * table[field] / table["Played"].clip(lower=1)
        custom = table[["Team", field, "Played"]].to_numpy()
        fig.add_trace(
            go.Bar(
                orientation="h", name=outcome,
                y=order, x=percentages, customdata=custom,
                marker=dict(color=OUTCOME_COLORS[outcome], line=dict(color="white", width=0.5)),
                text=[f"{p:.0f}%" if p >= 12 else "" for p in percentages],
                textposition="inside",
                textfont=dict(color=DARK if outcome == "Draw" else "white", size=10),
                hovertemplate=(
                    f"<b>%{{customdata[0]}}</b><br>{outcome}: %{{customdata[1]}}"
                    " of %{customdata[2]} matches<br>Share: %{x:.1f}%<extra></extra>"
                ),
            )
        )
    common_layout(fig)
    fig.update_layout(
        height=610,
        margin=dict(l=125, r=35, t=38, b=45),
        barmode="stack", bargap=0.22, dragmode=False,
        legend=dict(orientation="h", x=0, y=1.08),
        uniformtext_minsize=10, uniformtext_mode="hide",
    )
    fig.update_yaxes(categoryorder="array", categoryarray=order, autorange="reversed", fixedrange=True)
    fig.update_xaxes(title="Match outcomes (%)", range=[0, 100],
                     tickvals=[0, 25, 50, 75, 100], ticksuffix="%", fixedrange=True,
                     showgrid=True, gridcolor="#E9EEF4", zeroline=False)
    if chosen:
        fig.add_annotation(
            x=99, y=chosen, text="◀ Selected", xanchor="right", showarrow=False,
            font=dict(color=SELECTION, size=11), bgcolor="rgba(255,255,255,0.85)",
        )
    return fig


